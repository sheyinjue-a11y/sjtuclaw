"""Persistence boundary for durable Scheduler task state."""

from typing import Protocol

from sjtuclaw.models.runtime import RuntimeRequest
from sjtuclaw.models.scheduler import Occurrence, Task
from sjtuclaw.models.session import RunState


class TaskStore(Protocol):
    def create_task(self, task: Task) -> None: ...
    def load_task(self, task_id: str) -> Task: ...
    def list_tasks(self, *, archived: bool = False) -> tuple[Task, ...]: ...
    def save_task(self, task: Task) -> None: ...
    def delete_task(self, task_id: str) -> None: ...
    def create_occurrence(self, occurrence: Occurrence) -> None: ...
    def load_occurrence(self, task_id: str, occurrence_id: str) -> Occurrence: ...
    def save_occurrence(self, occurrence: Occurrence) -> None: ...
    def list_occurrences(
        self, task_id: str, *, cursor: str | None = None, limit: int = 50
    ) -> tuple[tuple[Occurrence, ...], str | None]: ...


class SchedulerRuntime(Protocol):
    """The small RuntimeHost surface used by SchedulerService."""

    async def submit(self, request: RuntimeRequest) -> object: ...

    def find_run(
        self,
        session_id: str,
        *,
        request_id: str | None = None,
        idempotency_key: str | None = None,
    ) -> RunState | None: ...

    async def cancel_queued(self, session_id: str, request_id: str) -> bool: ...

    async def stop_run(self, session_id: str, run_id: str) -> bool: ...
